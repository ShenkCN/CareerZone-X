# ============================================================
# 使用说明页：用户不需要懂 Swagger/API，也能完成求职闭环。
# 专门解释 8501（网站）和 8000（后端）的区别。
# ============================================================
from __future__ import annotations

import streamlit as st

from frontend import ui


def render_guide() -> None:
    """把最容易困惑的“怎么用/为什么没岗位”讲清楚。"""
    ui.page_header("使用说明", "先看这一页，再操作；不用打开 Swagger。")

    st.markdown(
        """
        ### 两个地址，别搞混
        - **http://127.0.0.1:8501**：这是你每天用的网站（登录、画像、职位、AI 分析）。
        - **http://127.0.0.1:8000**：这是后端 API，给前端/扩展调用；/api/docs 是开发者调试页，不是产品界面。

        你不需要在 Swagger 里点任何东西。Swagger 只用于开发排障；日常求职只用 8501。
        """
    )

    st.markdown("### 第一次使用：按顺序做")
    st.markdown(
        """
        1. **注册**普通账号（账号 5—15 位字母/数字；密码 6—20 位，纯数字/纯字母均可）。
        2. 用管理员 Shenk 登录，进“注册审核”通过你的账号。
        3. 用普通账号登录，填写“我的画像”（至少目标岗位或技能）。
        4. 上传 PDF/Word 简历，核对 AI 预填结果后保存。
        5. 设置 → 采集令牌 → 生成令牌；Edge 加载 extension 文件夹。
        6. 手动打开 BOSS/猎聘/智联/51JOB/鱼泡，点扩展“采集当前页”。
        7. 回职位板搜索/筛选，点详情做两轮 AI 分析，再决定投不投。
        """
    )

    st.markdown("### 为什么职位板是 0 条")
    st.markdown(
        """
        因为这个工具**不会自动爬招聘网站**。它只分析你已经采集/粘贴到本机的职位。
        你没有采集之前，职位库就是空的；点“搜索”只会搜这 0 条，所以看起来“没反应”。

        解决方式（任选）：
        - 用扩展采集当前页（推荐详情页）；
        - 在职位板底部“手动粘贴 JD”里贴职位原文；
        - 先从云计算/运维/技术支持等关键词开始，不必只搜 AI。
        """
    )

    st.markdown("### 管理员和普通用户的区别")
    st.markdown(
        """
        - 管理员 Shenk：审批、看 Token、反馈、导出、系统后端；不占用户职位板。
        - 普通用户：画像、简历、职位、收藏、历史、设置。
        - 管理员密码固定；密保问题可在管理员“安全与导出”里改。
        """
    )

    st.markdown("### 出错时怎么排")
    st.markdown(
        """
        - 注册提示密码规则：按提示改成 6 位以上并包含数字。
        - 提示请求过于频繁：等页面提示的分钟数；不要连续点。
        - 登录提示 401：刷新页面重新登录；会话默认 12 小时。
        - 职位为 0：先采集；扩展报错就把截图/报错发我。
        - AI 不可用：检查 .env 的 DeepSeek Key 和 /health 的 llm_configured。
        """
    )

    st.info("需要开发者文档时再看：http://127.0.0.1:8000/api/docs 。日常不需要。")
